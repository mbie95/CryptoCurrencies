package com.mobile.cryptocurrencies.app.portfolio.data.mapper

import com.mobile.cryptocurrencies.app.coins.data.model.Coin
import com.mobile.cryptocurrencies.app.portfolio.data.PortfolioCoinModel
import com.mobile.cryptocurrencies.app.portfolio.data.local.PortfolioCoinEntity
import kotlin.time.Clock
import kotlin.time.ExperimentalTime

fun PortfolioCoinEntity.toPortfolioCoinModel(
    currentPrice: Double,
): PortfolioCoinModel {
    return PortfolioCoinModel(
        coin = Coin(
            id = coinId,
            name = name,
            symbol = symbol,
            iconUrl = iconUrl
        ),
        performancePercent = ((currentPrice - averagePurchasePrice) / averagePurchasePrice) * 100,
        averagePurchasePrice = averagePurchasePrice,
        ownedAmountInUnit = amountOwned,
        ownedAmountInFiat = amountOwned * currentPrice
    )
}

@OptIn(ExperimentalTime::class)
fun PortfolioCoinModel.toPortfolioCoinEntity(): PortfolioCoinEntity {
    return PortfolioCoinEntity(
        coinId = coin.id,
        name = coin.name,
        symbol = coin.symbol,
        iconUrl = coin.iconUrl,
        amountOwned = ownedAmountInUnit,
        averagePurchasePrice = averagePurchasePrice,
        timestamp = Clock.System.now().toEpochMilliseconds()
    )
}